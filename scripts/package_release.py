#!/usr/bin/env python
# coding: utf-8
"""Package the XML of src/ for a GitHub Release (.github/workflows/release.yml).

Commands:
  check-tag TAG
      Exit with 0 if TAG is "v" + the content of VERSION, 1 otherwise. A
      Release is built only for the version that the repository declares.
  package --xml-dir DIR --dist DIST [--version X.Y.Z] --jiecc-version TEXT
      Make DIST/jieclib-X.Y.Z-<target>.zip for each target (omron and
      keyence) from DIR/<target>/src/ (the output of
      `python scripts/run_tests.py --compile-only --output-dir DIR src`).
      The paths in a zip are relative to src/ (math/floor.xml, ...). Each
      zip also has IMPORT_NOTES.txt with the Jiecc version and the notes on
      importing the XML. The version defaults to the VERSION file.

Usage:
  python scripts/package_release.py check-tag v4.1.0
  python scripts/package_release.py package --xml-dir out --dist dist --version 4.1.0 --jiecc-version "Jiecc 9.2.0"
"""
import argparse
import os
import sys
import zipfile

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
TARGETS = ('omron', 'keyence')
NOTES_NAME = 'IMPORT_NOTES.txt'

NOTES = '''JiecLib {version} - IEC 61131-10 XML for {target}

Generated by: {jiecc_version}
Source: https://github.com/yunos0987/jieclib/releases/tag/v{version}

Each XML file is one library of src/ (for example math/floor.xml from
src/math/floor.iec), compiled with "-t {target}". Import it with the
IEC 61131-10 import of the development environment (Sysmac Studio:
Tools | IEC 61131-10 XML | Import).

Notes on importing
- An XML file also contains the POUs and types of the files that its
  library includes (for example Console_* and Console_t of sys.iec). When
  you import several XML files into one project, the same POU is imported
  more than once. Import the XML of the libraries that you need, and skip
  or overwrite the POUs that the project already has.
- A zip has the libraries whose header comment declares the target
  ($ jiecc ... -t {target} in the .iec file of the repository).
- The templates (container, signal, ...) are not in these files: they need
  macros that only you can choose. Make them with Jiecc, as samples/ shows.

日本語の説明は README.md の「Sysmac StudioでJiecLib内のライブラリを取り込む方法」にあります。
'''


def read_version(root=_ROOT):
    # type: (str) -> str
    with open(os.path.join(root, 'VERSION'), encoding='utf-8') as f:
        return f.read().strip()


def check_tag(tag, version):
    # type: (str, str) -> bool
    return tag == 'v' + version


def package(xml_dir, dist, version, jiecc_version):
    # type: (str, str, str, str) -> list
    """Make the zips and return their paths. Raise ValueError when a target has no XML."""
    os.makedirs(dist, exist_ok=True)
    made = []
    for target in TARGETS:
        base = os.path.join(xml_dir, target, 'src')
        files = []
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            for name in sorted(filenames):
                if name.endswith('.xml'):
                    full = os.path.join(dirpath, name)
                    files.append((full, os.path.relpath(full, base).replace(os.sep, '/')))
        files.sort(key=lambda f: f[1])
        if not files:
            raise ValueError('no XML for {} in {}'.format(target, base))
        path = os.path.join(dist, 'jieclib-{}-{}.zip'.format(version, target))
        with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as zf:
            for full, arcname in files:
                zf.write(full, arcname)
            zf.writestr(NOTES_NAME, NOTES.format(version=version, target=target,
                                                  jiecc_version=jiecc_version))
        made.append(path)
    return made


def main(argv=None):
    # type: (list) -> int
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = parser.add_subparsers(dest='command')
    p_check = sub.add_parser('check-tag', help='check the tag against VERSION')
    p_check.add_argument('tag')
    p_pack = sub.add_parser('package', help='make the zips')
    p_pack.add_argument('--xml-dir', required=True)
    p_pack.add_argument('--dist', required=True)
    p_pack.add_argument('--version', default=None,
                        help='the version in the file names (default: the VERSION file)')
    p_pack.add_argument('--jiecc-version', required=True)
    args = parser.parse_args(argv)
    if args.command == 'check-tag':
        version = read_version()
        if check_tag(args.tag, version):
            print('Tag {} matches VERSION {}.'.format(args.tag, version))
            return 0
        print('error: tag {!r} does not match VERSION {!r} (expected v{}).'.format(
            args.tag, version, version))
        return 1
    if args.command == 'package':
        try:
            made = package(args.xml_dir, args.dist, args.version or read_version(),
                           args.jiecc_version)
        except ValueError as e:
            print('error: {}'.format(e))
            return 1
        for path in made:
            print('Made {}'.format(path))
        return 0
    parser.print_help()
    return 2


if __name__ == '__main__':
    sys.exit(main())
